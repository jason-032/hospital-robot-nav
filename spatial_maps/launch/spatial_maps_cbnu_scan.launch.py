#!/usr/bin/env python3
"""
Launch the 1F navigation configuration on the CBNU scan-derived map.

The map comes from the cbnu-scan2bim TLS study (11 spaces of the CBNU engineering
building, obstacles from the band 0.08 to 0.60 m above the floor, 0.05 m cells).
The Gazebo world is the outline of that map's occupied cells, so this run tests
whether the stack can drive the map. It does not test the map against the building.
Site files are generated by tools/cbnu_scan/build_site.py.

Usage:
  ros2 launch spatial_maps spatial_maps_cbnu_scan.launch.py headless:=true rviz:=false

Launch, check and sweep the 11 spaces in one go:
  bash tools/cbnu_scan/run_trial.sh <label>   (starts its own launch)
"""

import os
import yaml
from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, IncludeLaunchDescription
from launch.launch_description_sources import PythonLaunchDescriptionSource
from launch.substitutions import LaunchConfiguration
from ament_index_python.packages import get_package_share_directory


def generate_launch_description():
    share = get_package_share_directory('spatial_maps')
    site = yaml.safe_load(open(os.path.join(share, 'config', 'cbnu_scan_site.yaml')))
    scan_map = os.path.join(share, 'maps', 'CBNU_scan.yaml')

    return LaunchDescription([
        DeclareLaunchArgument('headless', default_value='false'),
        DeclareLaunchArgument('rviz', default_value='true'),
        # Wheel-inclusive footprint, unknown space blocked, wider planning margin.
        DeclareLaunchArgument('params_overlay', default_value=os.path.join(
            share, 'config', 'nav2_params_cbnu_scan.yaml')),
        IncludeLaunchDescription(
            PythonLaunchDescriptionSource(
                os.path.join(share, 'launch', 'spatial_maps_1f.launch.py')),
            launch_arguments={
                'world':           os.path.join(share, 'worlds', 'cbnu_scan.world'),
                'bridge_config':   os.path.join(share, 'config', 'gz_bridge_cbnu_scan.yaml'),
                'map_yaml':        scan_map,
                # Already 0.05 m, the resolution the lattice planner needs.
                'map_yaml_global': scan_map,
                'speed_mask_yaml': os.path.join(share, 'maps', 'CBNU_scan_speed_mask.yaml'),
                'semantic_json':   os.path.join(share, 'config', 'cbnu_scan_rooms.json'),
                'floor':           'CBNU_scan',
                'spawn_x':         str(site['spawn_x']),
                'spawn_y':         str(site['spawn_y']),
                'spawn_yaw':       str(site['spawn_yaw']),
                'headless':        LaunchConfiguration('headless'),
                'rviz':            LaunchConfiguration('rviz'),
                'params_overlay':  LaunchConfiguration('params_overlay'),
            }.items()),
    ])
